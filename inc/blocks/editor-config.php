function theme_get_posts_for_block_editor(string $post_type): array
{
    $posts = get_posts([
        'post_type'      => $post_type,
        'posts_per_page' => 200,
        'post_status'    => 'publish',
        'orderby'        => 'title',
        'order'          => 'ASC',
    ]);

    $items = [];

    foreach ($posts as $post) {
        $items[] = [
            'id'    => $post->ID,
            'label' => $post->post_title,
        ];
    }

    return $items;
}

